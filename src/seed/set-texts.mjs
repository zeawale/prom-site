const LIMIT_D = 165
const LIMIT_H = 86

const file = 'src/seed/1c_services_catalog.json'
const data = JSON.parse(fs.readFileSync(file, 'utf-8'))

const missed = []
let d = 0
let h = 0

for (const svc of data) {
  const desc = DESCRIPTIONS[svc.id]
  const head = HEADLINES[svc.id]
  if (desc) {
    svc.description = desc
    d++
  } else {
    missed.push(svc.id)
  }
  if (head) {
    svc.headline = head
    h++
  }
}

// Контроль: ничего не должно превышать лимиты
const longD = data.filter((s) => s.description.length > LIMIT_D)
const longH = data.filter((s) => s.headline.length > LIMIT_H)

fs.writeFileSync(file, JSON.stringify(data, null, 2), 'utf-8')

console.log(`Описаний обновлено: ${d} из ${data.length}`)
console.log(`Заголовков обновлено: ${h}`)
if (missed.length) console.log('Без нового описания:', missed)
if (longD.length)
  console.log(
    `Описания длиннее ${LIMIT_D}:`,
    longD.map((s) => `${s.id} (${s.description.length})`),
  )
if (longH.length)
  console.log(
    `Заголовки длиннее ${LIMIT_H}:`,
    longH.map((s) => `${s.id} (${s.headline.length})`),
  )
if (!longD.length && !longH.length) console.log('Все тексты в пределах лимитов')
