/* Авторы четырёх выдуманных отзывов, стоявших до 01.10.2026. На базе, где
   сид уже отрабатывал, они остались бы рядом с настоящими */
const REMOVED_AUTHORS = ['Ирина Кузнецова', 'Ольга Демидова', 'Сергей Гаврилов', 'Марина Соколова']

const seed = async () => {
  const payload = await getPayload({ config })

  await payload.delete({
    context: { disableRevalidate: true },
    collection: 'reviews',
    where: { author: { in: REMOVED_AUTHORS } },
  })

  for (const review of REVIEWS) {
    const { docs } = await payload.find({
      collection: 'reviews',
      where: { author: { equals: review.author } },
      limit: 1,
    })

    const data = { ...review, showOnHome: true }

    if (docs[0]) {
      await payload.update({
        context: { disableRevalidate: true },
        collection: 'reviews',
        id: docs[0].id,
        data,
      })
    } else {
      await payload.create({
        context: { disableRevalidate: true },
        collection: 'reviews',
        data,
      })
    }
  }

  console.log(`Отзывы: записано ${REVIEWS.length}`)
  process.exit(0)
}

process.on('unhandledRejection', (e) => {
  console.error('UNHANDLED REJECTION:', e)
  process.exit(1)
})

seed().catch((e) => {
  console.error('ОШИБКА В SEED:', e)
  process.exit(1)
})
