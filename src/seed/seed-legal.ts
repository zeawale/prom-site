const DOCS = [privacy, cookie, consent]

const seed = async () => {
  const payload = await getPayload({ config })

  // Идемпотентность: документов ровно три, ищем по слагу и обновляем.
  // Полная очистка коллекции здесь была бы лишней — слаг уникален
  for (const doc of DOCS) {
    const existing = await payload.find({
      collection: 'legal-pages',
      where: { slug: { equals: doc.slug } },
      limit: 1,
      depth: 0,
    })

    if (existing.docs[0]) {
      await payload.update({
        collection: 'legal-pages',
        id: existing.docs[0].id,
        context: { disableRevalidate: true },
        data: doc,
      })
      console.log(`  /${doc.slug} — обновлён, разделов: ${doc.sections.length}`)
    } else {
      await payload.create({
        collection: 'legal-pages',
        context: { disableRevalidate: true },
        data: doc,
      })
      console.log(`  /${doc.slug} — создан, разделов: ${doc.sections.length}`)
    }
  }

  console.log(`\nВерсия согласия: ${CONSENT_VERSION}`)
  console.log('\nТРЕБУЕТ ПОДТВЕРЖДЕНИЯ ДМИТРИЕМ ДО ПУБЛИКАЦИИ:')
  console.log('  1. Почтовый индекс в адресе (603163 взят по Казанскому шоссе, проверить)')
  console.log('  2. ОГРН — в документах не упомянут, поле в Settings пустое')
  console.log('  3. Срок хранения заявок: сейчас три года с последнего обращения')
  console.log('  4. Хостинг-провайдер как третье лицо: назван обобщённо, вписать после выбора')
  console.log('  5. Ответственный за организацию обработки ПДн — назначить приказом')
  console.log('  6. Уведомление в реестр операторов РКН — подать до начала сбора заявок')
  console.log('\nТексты — черновики. Перед публикацией вычитывает юрист.')
  process.exit(0)
}

