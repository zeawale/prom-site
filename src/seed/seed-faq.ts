const faq = (items: Item[]) => ({ title: TITLE, items })

const seed = async () => {
  const payload = await getPayload({ config })
  const context = { disableRevalidate: true }

  await payload.updateGlobal({ context, slug: 'fresh', data: { faq: faq(FRESH) } })
  await payload.updateGlobal({ context, slug: 'its', data: { faq: faq(ITS) } })
  await payload.updateGlobal({ context, slug: 'grm', data: { faq: faq(GRM) } })

  const missing: string[] = []
  for (const [slug, items] of Object.entries(PROGRAMS)) {
    const { docs } = await payload.update({
      context,
      collection: 'programs',
      where: { slug: { equals: slug } },
      data: { faq: faq(items) },
    })
    if (!docs.length) missing.push(slug)
  }

  if (missing.length) {
    console.warn(`Не найдены программы (сначала pnpm seed:programs):\n  ${missing.join('\n  ')}`)
  }

  const programCount = Object.keys(PROGRAMS).length - missing.length
  console.log(`Вопросы записаны: /fresh, /its, /grm и ${programCount} программ.`)
  process.exit(0)
}

process.on('unhandledRejection', (e) => {
  console.error('UNHANDLED REJECTION:', e)
  process.exit(1)
})

seed().catch((e) => {
  console.error('ОШИБКА В SEED:', e)
  process.exit(1)
})
