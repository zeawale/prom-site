import 'dotenv/config'
import { getPayload } from 'payload'
import config from '../payload.config'

/**
 * Контент страниц /about и /contacts. Тексты сняты с макета.
 *
 * Один сид на две страницы: обе маленькие, обе состоят из одного глобала,
 * и запускать их по отдельности незачем.
 *
 * Правки против макета, сделанные сознательно:
 *  — кавычки-ёлочки и длинные тире, как в остальных сидах;
 *  — в карточках «Контактов» лежат только заголовки и подписи. Сами
 *    телефон, почта, часы, адрес, юрлицо и ИНН приходят из глобала
 *    Settings — того же, что кормит шапку и футер.
 *
 * Что осталось на проверку у Дмитрия, тексты записаны как в макете:
 *  — «20+ лет на рынке» рядом с «2014 год основания». В 2026 году от
 *    2014-го прошло двенадцать лет, а первый абзац прямо говорит, что
 *    компанию основали в 2014-м. Либо счётчик считает опыт команды,
 *    и подпись надо переписать, либо цифра неверная;
 *  — четвёртый абзац «О компании» («Наша миссия заключается в создании
 *    условий…») выбивается из тона остальных трёх — это канцелярит,
 *    который по правилам проекта из текстов вычищается.
 */
const seed = async () => {
  const payload = await getPayload({ config })

  await payload.updateGlobal({
    context: { disableRevalidate: true },
    slug: 'about',
    data: {
      title: 'ООО «НПП ПРО-М»: сопровождаем 1С у малого бизнеса Нижнего Новгорода',

      body: [
        'Мы основали НПП «ПРО-М» в 2014 году. Официальный статус партнёра «1С» — с 2014 года. Разрабатываем решения 1С, сопровождаем учёт и помогаем перейти на 1С:Фреш и облачные сервисы — из коробки и с индивидуальной настройкой.',
        'ПРО-М не продаёт лицензии ради продажи. Мы подбираем конфигурацию 1С так, чтобы она реально помогла именно вашему бизнесу. Если вам не нужен дорогой модуль — мы скажем об этом прямо.',
        'Основатель компании — инженер. Поэтому всё, что мы делаем, начинается с вопроса «Как это должно работать у вас?», а не «Что мы можем продать?»',
        'Наша миссия заключается в создании условий для клиентов, которые помогут им в оптимизации бизнес-процессов и сокращении расходов.',
      ].join('\n'),

      counters: [
        { value: '20+', caption: 'лет на рынке ИТ-аутсорсинга' },
        { value: '2014', caption: 'год основания НПП «ПРО-М»' },
        { value: '300+', caption: 'клиентов на постоянной поддержке' },
        { value: '1200+', caption: 'выполненных проектов и внедрений' },
      ],

      reviewsTitle: 'Отзывы клиентов',
      reviewsLead:
        'Клиенты, которые однажды начали, остаются с нами годами: добросовестная поддержка базы 1С, персональный менеджер и быстрые ответы.',
    },
  })

  await payload.updateGlobal({
    context: { disableRevalidate: true },
    slug: 'contacts',
    data: {
      title: 'Контакты',
      lead: 'Звоните в рабочее время: по телефону разбираем ситуацию сразу. Без заявки и переписки.',

      phone: { label: 'Телефон', caption: 'Разберём вашу ситуацию сразу' },
      email: { label: 'Почта', caption: 'Ответим в течение рабочего дня' },
      hours: { label: 'Часы работы', caption: 'Суббота и воскресенье — на отдыхе' },
      address: { label: 'Адрес офиса', caption: null },
      legal: { label: 'Юридическое лицо', caption: 'Договор и счёт выставляем от этого лица' },
      inn: { label: 'ИНН', caption: 'Остальные реквизиты — в счёте и договоре' },

      map: {
        url: 'https://yandex.ru/map-widget/v1/?text=%D0%9D%D0%B8%D0%B6%D0%BD%D0%B8%D0%B9%20%D0%9D%D0%BE%D0%B2%D0%B3%D0%BE%D1%80%D0%BE%D0%B4%2C%20%D0%9A%D0%B0%D0%B7%D0%B0%D0%BD%D1%81%D0%BA%D0%BE%D0%B5%20%D1%88%D0%BE%D1%81%D1%81%D0%B5%2C%2012%20%D0%BA.1&z=17&lang=ru_RU',
        plaque: 'ПРО-М — Казанское шоссе, 12 к.1, офис 311',
        buttonLabel: 'Показать карту',
        note: 'Карта загружается с серверов Яндекса и ставит свои cookie. Нажмите, чтобы открыть её.',
      },
    },
  })

  console.log('Страницы /about и /contacts записаны.')
  console.log('Отзывы живут в коллекции Reviews — они пишутся командой pnpm seed:reviews')
  process.exit(0)
}

process.on('unhandledRejection', (e) => {
  console.error('UNHANDLED REJECTION:', e)
  process.exit(1)
})

seed().catch((e) => {
  console.error('ОШИБКА В SEED:', e)
  process.exit(1)
})
