/**
 * Публичный адрес сайта — одно место для всех, кому нужен абсолютный URL:
 * metadataBase в корневом layout, sitemap, robots и сведение доменов в proxy.
 *
 * Берётся из NEXT_PUBLIC_SITE_URL, потому что на превью-стенде домен
 * другой, а зашитый прод молча подставился бы в canonical и в ссылки
 * предпросмотра. Фолбэк — с www: именно этот вариант домена
 * проиндексирован, к нему сводится всё (см. «Переезд со старого сайта»).
 *
 * Без завершающего слэша: new URL('/x', SITE_URL) и `${SITE_URL}/x`
 * должны давать одно и то же.
 */
export const SITE_URL = (process.env.NEXT_PUBLIC_SITE_URL ?? 'https://www.pm52.ru').replace(
  /\/+$/,
  '',
)
